REGEX_REPLACEMENTS = [
    (re.compile(r"第\s*(\d+)\s*页"), r"Page \1"),
    (re.compile(r"幻灯片\s*(\d+)"), r"Slide \1"),
    (re.compile(r"段落\s*(\d+)"), r"Paragraph \1"),
    (re.compile(r"Word 评论\s*([^\s]+)"), r"Word Comment \1"),
    (re.compile(r"(\d+)\s*个文件"), r"\1 files"),
    (re.compile(r"(\d+)\s*个对象"), r"\1 objects"),
    (re.compile(r"(\d+)\s*个构件"), r"\1 elements"),
    (re.compile(r"(\d+)\s*个附件"), r"\1 attachments"),
    (re.compile(r"(\d+)\s*个"), r"\1 items"),
    (re.compile(r"(\d+)\s*项(?!目)"), r"\1 items"),
    (re.compile(r"(\d+)\s*条"), r"\1 items"),
    (re.compile(r"已生成批注\s*(\S*)"), r"Annotation generated \1"),
]


def localize_text(value):
    if not english_report() or not isinstance(value, str) or not value:
        return value
    result = value
    for zh, en in sorted(PHRASES.items(), key=lambda item: len(item[0]), reverse=True):
        result = result.replace(zh, en)
    for pattern, replacement in REGEX_REPLACEMENTS:
        result = pattern.sub(replacement, result)
    return (
        result.replace("：", ": ")
        .replace("；", "; ")
        .replace("、", ", ")
        .replace("（", " (")
        .replace("）", ")")
    )


def localize_workbook(workbook):
    if not english_report():
        return workbook
    for sheet in workbook.worksheets:
        title = localize_text(sheet.title)
        sheet.title = str(title or sheet.title)[:31]
        for row in sheet.iter_rows():
            for cell in row:
                if isinstance(cell.value, str):
                    cell.value = localize_text(cell.value)
    return workbook
